#!/usr/bin/env python3
"""Generate SDP expectations and dataset-level checks from a spec's `dq` block.

Usage:  python3 expectations_from_spec.py spec.json > expectations.py
Prints a Python module (row expectations) and a SQL uniqueness check to stdout.
Identifiers are validated, so spec values cannot inject SQL.
"""
import json
import re
import sys

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def ident(name):
    if not IDENT.match(name or ""):
        raise ValueError(f"not a plain column name: {name!r}")
    return name


def expectations(spec):
    dq = spec.get("dq") or {}
    fail, drop, warn = {}, {}, {}
    for col in dq.get("not_null") or []:
        fail[f"not_null_{ident(col)}"] = f"{col} IS NOT NULL"
    for rng in dq.get("ranges") or []:
        col = ident(rng.get("column"))
        parts = []
        if rng.get("min") is not None:
            parts.append(f"{col} >= {float(rng['min'])}")
        if rng.get("max") is not None:
            parts.append(f"{col} <= {float(rng['max'])}")
        if not parts:
            continue
        expr = " AND ".join(parts)
        bucket = {"fail": fail, "drop": drop, "warn": warn}.get(rng.get("action", "drop"), drop)
        bucket[f"range_{col}"] = expr
    return fail, drop, warn


def render(spec):
    fail, drop, warn = expectations(spec)
    table = (spec.get("target") or {}).get("table", "<table>")
    lines = [
        "# Generated by expectations_from_spec.py. Do not hand-edit; regenerate from the spec.",
        f"# Target: {table}",
        f"EXPECT_FAIL = {json.dumps(fail, indent=4)}",
        f"EXPECT_DROP = {json.dumps(drop, indent=4)}",
        f"EXPECT_WARN = {json.dumps(warn, indent=4)}",
        "",
        "# Usage on the silver definition:",
        "# @dp.expect_all_or_fail(EXPECT_FAIL)",
        "# @dp.expect_all_or_drop(EXPECT_DROP)",
        "# @dp.expect_all(EXPECT_WARN)",
        "",
    ]
    keys = (spec.get("dq") or {}).get("unique") or []
    if keys:
        cols = ", ".join(ident(k) for k in keys)
        lines += [
            "# Dataset check (run after the load; must return zero rows):",
            f"# SELECT {cols}, COUNT(*) AS n FROM <catalog>.<schema>.{table}",
            f"#   GROUP BY {cols} HAVING COUNT(*) > 1;",
        ]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    with open(sys.argv[1], encoding="utf-8") as fh:
        spec = json.load(fh)
    try:
        print(render(spec))
    except ValueError as exc:
        print(f"invalid spec: {exc}", file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
